/*
  Lesson self-check quizzes.

  Deliberately separate from learn-progress.js: nothing here reads or writes progress state,
  nothing is stored, nothing leaves the page. A quiz is a self-check, not an assessment, and
  coupling it to completion tracking would mean a wrong answer could block a lesson.

  Markup contract (generated by generate-learn-pages.js):
    .lesson-quiz > ol.quiz-list > li.quiz-q
      button.quiz-option[data-correct="1|0"]
      p.quiz-explain[hidden]
    p[data-quiz-score]

  No-ops silently when there is no quiz on the page.
*/
(function () {
  'use strict';

  function init() {
    var quiz = document.querySelector('.lesson-quiz');
    if (!quiz) return;

    var questions = Array.prototype.slice.call(quiz.querySelectorAll('.quiz-q'));
    if (!questions.length) return;

    var answered = 0, correct = 0;
    var scoreEl = quiz.querySelector('[data-quiz-score]');

    questions.forEach(function (q) {
      var options = Array.prototype.slice.call(q.querySelectorAll('.quiz-option'));
      var explain = q.querySelector('.quiz-explain');

      options.forEach(function (btn) {
        btn.addEventListener('click', function () {
          if (q.classList.contains('is-answered')) return;
          q.classList.add('is-answered');

          var isRight = btn.getAttribute('data-correct') === '1';
          btn.classList.add(isRight ? 'is-correct' : 'is-wrong');

          // Always reveal the correct option, so a wrong answer still teaches something.
          options.forEach(function (o) {
            o.disabled = true;
            if (o.getAttribute('data-correct') === '1') o.classList.add('is-answer');
          });

          if (explain) explain.hidden = false;

          answered++;
          if (isRight) correct++;
          if (scoreEl && answered === questions.length) {
            scoreEl.hidden = false;
            scoreEl.textContent = correct + ' of ' + questions.length + ' correct.'
              + (correct === questions.length ? ' Move on to the next lesson.' : ' Worth a re-read of the sections above before moving on.');
          }
        });
      });
    });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
